/**
 * Documentation derived from the system (Pattern 14).
 *
 * Generates the parts of the docs that the code already knows (the data model and its ERD, every playbook as a
 * flowchart, the API table, the gates, the coverage charts) and keeps two-way links between tests and docs: every
 * test file names the doc it verifies, and every doc lists the tests that verify it. `--check` fails when a doc is
 * stale, a test names a doc that does not exist, or a doc has no test.
 */
const DOCS = join(ROOT, 'docs');
const mermaidId = (s: string) => s.replace(/[^A-Za-z0-9_]/g, '_');

const walk = (dir: string, keep: (p: string) => boolean): string[] =>
  existsSync(dir)
    ? readdirSync(dir).flatMap((n) => {
        const p = join(dir, n);
        if (n === 'node_modules' || n.startsWith('.')) return [];
        return statSync(p).isDirectory() ? walk(p, keep) : keep(p) ? [p] : [];
      })
    : [];

