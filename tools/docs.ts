export function coveragePage(): string {
  const read = <T>(f: string): T | undefined => (existsSync(join(ROOT, 'evidence-out', f)) ? (JSON.parse(readFileSync(join(ROOT, 'evidence-out', f), 'utf8')) as T) : undefined);
  const ex = read<{ seeds: { name: string; states: number; transitions: number; exhausted: boolean }[]; states: number; transitions: number; violations: unknown[]; verbsSeen: Record<string, number> }>('explore.json');
  const cr = read<{ seeds: { name: string; states: number; transitions: number; exhausted: boolean }[]; states: number; transitions: number; violations: unknown[]; routes: string[] }>('crawl.json');
  const tests = read<{ numTotalTests: number; testResults: { name: string; assertionResults: unknown[] }[] }>('tests.json');
  const own = (s: { name: string }) => !s.name.includes('/');
  const bar = (title: string, seeds: { name: string; transitions: number }[]) =>
    `\`\`\`mermaid\nxychart-beta\n  title "${title}"\n  x-axis [${seeds.map((s) => `"${s.name}"`).join(', ')}]\n  y-axis "Transitions"\n  bar [${seeds.map((s) => s.transitions).join(', ')}]\n\`\`\``;
  const byPkg = new Map<string, number>();
  for (const t of tests?.testResults ?? []) {
    const k = relative(ROOT, t.name).split('/').slice(0, 2).join('/');
    byPkg.set(k, (byPkg.get(k) ?? 0) + t.assertionResults.length);
  }
  return `# Coverage

<!-- generated by tools/docs.ts from the last walk, crawl and test reports; do not edit by hand -->

${tests ? `## Tests by package\n\n\`\`\`mermaid\npie showData title ${tests.numTotalTests} tests\n${[...byPkg].sort((a, b) => b[1] - a[1]).map(([k, n]) => `  "${k}" : ${n}`).join('\n')}\n\`\`\`\n` : 'No test report yet. Run `npm run evidence`.\n'}
${ex ? `## Button walk\n\n${ex.states.toLocaleString('en-US')} states and ${ex.transitions.toLocaleString('en-US')} transitions across ${ex.seeds.length} seeds; ${ex.seeds.every((s) => s.exhausted) ? 'every seed ran to its fixpoint' : 'some seeds were cut short'}; ${ex.violations.length} violations.\n\n${bar('Button walk: transitions per student', ex.seeds.filter(own))}\n\n| Verb | Times tried |\n| --- | --- |\n${Object.entries(ex.verbsSeen).sort((a, b) => b[1] - a[1]).map(([v, n]) => `| \`${v}\` | ${n.toLocaleString('en-US')} |`).join('\n')}\n` : 'No button walk report yet. Run `npm run explore`.\n'}
${cr ? `## Feature walk\n\n${cr.states.toLocaleString('en-US')} page-states and ${cr.transitions.toLocaleString('en-US')} links and forms across ${cr.seeds.length} seeds; ${cr.violations.length} violations. Routes reached: ${cr.routes.map((r) => `\`${r}\``).join(', ')}.\n\n${bar('Feature walk: links and forms followed per student', cr.seeds.filter(own))}\n` : 'No feature walk report yet. Run `npm run crawl`.\n'}
## Verified by

<!-- verified-by:start -->
<!-- verified-by:end -->
`;
}

import { links, type Links } from './doc-links.js';

const countTests = (file: string) => (readFileSync(join(ROOT, file), 'utf8').match(/\b(it|it\.each\([^)]*\))\(/g) ?? []).length;

export function fillVerifiedBy(body: string, doc: string, l: Links): string {
  const tests = [...l.testsToDocs].filter(([, ds]) => ds.includes(doc)).map(([t]) => t).sort();
  const depth = doc.split('/').length - 1;
  const up = '../'.repeat(depth);
  const list = tests.length ? tests.map((t) => `- [\`${t}\`](${up}${t}) (${countTests(t)} test definitions)`).join('\n') : '- None yet.';
  return body.replace(/<!-- verified-by:start -->[\s\S]*?<!-- verified-by:end -->/, `<!-- verified-by:start -->\n${list}\n<!-- verified-by:end -->`);
}

export function indexPage(): string {
  const docs = walk(DOCS, (p) => p.endsWith('.md') && !p.endsWith('README.md')).map((p) => relative(DOCS, p)).sort();
  const title = (p: string) => readFileSync(join(DOCS, p), 'utf8').match(/^# (.+)$/m)?.[1] ?? p;
  const group = (prefix: string) => docs.filter((d) => (prefix ? d.startsWith(prefix) : !d.includes('/')));
  const section = (name: string, list: string[]) => (list.length ? `## ${name}\n\n${list.map((d) => `- [${title(d)}](${d})`).join('\n')}\n` : '');
  return `# Documentation

<!-- generated by tools/docs.ts; do not edit by hand -->

\`\`\`mermaid
flowchart LR
  arch[Architecture] --> agents[Agent team] --> flows[Business flows]
  arch --> data[Data model]
  arch --> api[Integration API]
  arch --> blocks[Building blocks]
  flows & data & api --> testing[How it is tested]
  testing --> coverage[Coverage]
\`\`\`

${section('The system', group(''))}
${section('Business flows', group('flows/'))}
${section('How it is tested', group('testing/'))}
${section('Building blocks', group('blocks/'))}
${section('Decisions', group('adr/'))}
Every test file names the document it verifies, and every document lists its tests. The \`docs-linked\` gate fails
the build when either side is missing.
`;
}

