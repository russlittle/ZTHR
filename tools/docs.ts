export async function buildDocs(check: boolean): Promise<string[]> {
  const { gateCatalog } = await import('./gates.js');
  const generated: Record<string, string> = {
    'docs/data-model.md': dataModel(),
    'docs/flows/playbooks.md': playbooksPage(),
    'docs/testing/gates.md': gatesPage(gateCatalog()),
    'docs/testing/coverage.md': coveragePage(),
  };
  const problems: string[] = [];
  const write = (file: string, body: string) => {
    const path = join(ROOT, file);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (current === body) return;
    if (check && !file.endsWith('coverage.md')) problems.push(`${file} is stale; run npm run docs`);
    if (!check) {
      mkdirSync(join(path, '..'), { recursive: true });
      writeFileSync(path, body);
    }
  };
  for (const [f, b] of Object.entries(generated)) {
    const existing = existsSync(join(ROOT, f)) ? readFileSync(join(ROOT, f), 'utf8') : '';
    // Keep the current verified-by list; it is filled below.
    const keep = existing.match(/<!-- verified-by:start -->[\s\S]*?<!-- verified-by:end -->/)?.[0];
    write(f, keep ? b.replace(/<!-- verified-by:start -->[\s\S]*?<!-- verified-by:end -->/, keep) : b);
  }
  const api = join(ROOT, 'docs/api.md');
  write('docs/api.md', readFileSync(api, 'utf8').replace(/<!-- generated:api:start -->[\s\S]*?<!-- generated:api:end -->/, apiTable()));
  const l = links();
  problems.push(...l.problems);
  for (const d of walk(DOCS, (p) => p.endsWith('.md')).map((p) => relative(ROOT, p))) {
    const body = readFileSync(join(ROOT, d), 'utf8');
    if (body.includes('<!-- verified-by:start -->')) write(d, fillVerifiedBy(body, d, l));
  }
  write('docs/README.md', indexPage());
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const problems = await buildDocs(check);
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  console.log(check ? 'docs are current and every test and doc is linked' : 'docs generated');
}
