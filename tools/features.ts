import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';
import { CONTROL } from './lib.js';

/** The features list, declared once in control/features.yaml; docs/features.md and the console are drawn from it. */
export interface Feature { name: string; what: string; status: 'built' | 'partial' | 'not measured'; screens: string[]; journeys: string[] }
export interface Phase { n: number; name: string; features: Feature[] }
export const loadFeatures = (): Phase[] => (parse(readFileSync(join(CONTROL, 'features.yaml'), 'utf8')) as { phases: Phase[] }).phases;

export function featuresPage(): string {
  const phases = loadFeatures();
  const all = phases.flatMap((p) => p.features);
  const count = (s: Feature['status']) => all.filter((f) => f.status === s).length;
  const mind = ['mindmap', '  root((Student Advocate))', ...phases.flatMap((p) => [`    P${p.n}[Phase ${p.n}: ${p.name}]`, ...p.features.map((f) => `      ${f.name.replace(/[()[\]{}]/g, '').replace(/,/g, '')}`)])].join('\n');
  return `# Features

<!-- generated by tools/features.ts from control/features.yaml; do not edit by hand -->

Everything the Student Advocate does, by phase. ${all.length} features: ${count('built')} built, ${count('partial')} partial, ${count('not measured')} not measured. Each names the locked journeys that prove it; the factory console shows whether each journey passed in this build.

\`\`\`mermaid
${mind}
\`\`\`

${phases.map((p) => `## Phase ${p.n}: ${p.name}

| Feature | What it does | Where | Status | Proven by |
| --- | --- | --- | --- | --- |
${p.features.map((f) => `| ${f.name} | ${f.what} | ${f.screens.join(', ') || 'background'} | ${f.status} | ${f.journeys.map((j) => `\`${j}\``).join(', ') || 'tests and gates'} |`).join('\n')}`).join('\n\n')}

## Verified by

<!-- verified-by:start -->
<!-- verified-by:end -->
`;
}
