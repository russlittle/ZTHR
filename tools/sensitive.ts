import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CLASSES, collectionClass, erd, type DataClass } from '@zthr/store';
import { COLLECTIONS, SEALED_FACTS } from '../apps/advocate/src/domain/schema.js';
import { POLICY, SINKS, runTrace } from '../apps/advocate/test/harness/trace.js';
import { OUT, headCommit } from './lib.js';

/**
 * The sensitive-data page (generated) and the trace run that the console shows.
 *   npx tsx tools/sensitive.ts      run the canary trace and write evidence-out/sensitive-trace.json
 */
const MEANS: Record<DataClass, string> = {
  public: 'Published facts anyone may read',
  internal: 'Ids, times, statuses and settings that say nothing about the student alone',
  personal: 'Identifies or describes the student: name, phone, schedule, what they wrote',
  sensitive: 'Special-category: money, benefits, family, identity, which help they need, sealed facts',
  secret: 'Credentials: stored only hashed or encrypted, never shown',
};

export function sensitivePage(): string {
  const fields = COLLECTIONS.flatMap((c) => c.fields.map((f) => ({ c: c.name, f: f.name, cls: f.cls as DataClass, note: f.note ?? '' })));
  const count = (k: DataClass) => fields.filter((x) => x.cls === k).length;
  const pie = ['pie showData title Fields by class', ...CLASSES.filter((k) => count(k)).map((k) => `  "${k}" : ${count(k)}`)].join('\n');
  const flow = ['flowchart LR', '  P[personal]:::p', '  S[sensitive]:::s', '  X[secret]:::x',
    ...SINKS.map((s, i) => `  k${i}[${s}]`),
    ...SINKS.flatMap((s, i) => [POLICY.personal.includes(s) ? `  P --> k${i}` : '', POLICY.sensitive.includes(s) ? `  S --> k${i}` : '']).filter(Boolean),
    '  X -. hashed or encrypted only .-> k0',
    '  classDef p fill:#dbeafe,stroke:#1d4ed8', '  classDef s fill:#fde68a,stroke:#b45309', '  classDef x fill:#fecaca,stroke:#b91c1c'].join('\n');
  const groups = [...new Set(COLLECTIONS.map((c) => c.group ?? 'student'))];
  return `# Sensitive data

<!-- generated by tools/sensitive.ts from apps/advocate/src/domain/schema.ts and the trace policy; do not edit by hand -->

Every field the Advocate keeps is classified, and every build proves where the personal, sensitive and secret ones
actually go. A unique marker is planted in each such field; a student then uses the app by text, on the web,
through the API, with a mentor introduction sent and a webhook registered; and every place data can land is
searched for every marker. A marker found anywhere its class may not go fails the \`sensitive-data\` gate, naming
the field and the place. The latest run is on the factory console's Sensitive data trace page.

## The classes

| Class | Means | Fields |
| --- | --- | --- |
${CLASSES.map((k) => `| ${k} | ${MEANS[k]} | ${count(k)} |`).join('\n')}

\`\`\`mermaid
${pie}
\`\`\`

## Where each class may go

\`\`\`mermaid
${flow}
\`\`\`

| Place | Personal | Sensitive | Secret |
| --- | --- | --- | --- |
${SINKS.map((s) => `| ${s} | ${POLICY.personal.includes(s) ? 'yes' : 'no'} | ${POLICY.sensitive.includes(s) ? 'yes' : 'no'} | no |`).join('\n')}

A field may declare one more place for itself, with a reason: the student's first name and the note they approved
go to the mentor platform; their class-site token goes to the class site; their webhook address receives webhooks.

## How it stays out

\`\`\`mermaid
flowchart TB
  in[A fact comes in] --> q{Class}
  q -- personal or sensitive --> store[(App store, owned by the student)]
  q -- sealed fact --> sealed[(Sealed store: encrypted per student, opened only by granted identities)]
  q -- secret --> hash[Hashed or encrypted; never shown, not even in the student's export]
  store --> own[Back to the student: screens, texts, export, API]
  store -. approved exact text only .-> out[Sent with approval]
  store -. never .-> ev[(Evidence: keyed-hash subjects, no content)]
  store -. never .-> led[(Consent ledger: short hashes, never labels or names)]
  store -. never .-> adm[App admin and outcomes: counts of five or more only]
\`\`\`

## Personal, sensitive and secret fields

| Field | Class | Note |
| --- | --- | --- |
${fields.filter((x) => ['personal', 'sensitive', 'secret'].includes(x.cls)).map((x) => `| \`${x.c}.${x.f}\` | ${x.cls} | ${x.note} |`).join('\n')}

## Sealed facts

| Fact | Class | Why it is sealed |
| --- | --- | --- |
${SEALED_FACTS.map((s) => `| \`${s.fact}\` | ${s.cls} | ${s.why} |`).join('\n')}

## The record, by sensitivity

Each field's class is shown beside it. A collection is as sensitive as its most sensitive field.

| Collection | Most sensitive field |
| --- | --- |
${COLLECTIONS.map((c) => `| \`${c.name}\` | ${collectionClass(c)} |`).join('\n')}

${groups.map((g) => `### ${g}\n\n\`\`\`mermaid\n${erd(COLLECTIONS.filter((c) => (c.group ?? 'student') === g), { showClass: true })}\n\`\`\``).join('\n\n')}

## Verified by

<!-- verified-by:start -->
<!-- verified-by:end -->
`;
}

if (process.argv[1]?.endsWith('sensitive.ts')) {
  const r = await runTrace();
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, 'sensitive-trace.json'), JSON.stringify({ ...r, commit: headCommit() }, null, 1));
  console.log(`${r.canaries.length} markers planted, ${r.findings.length} sightings, ${r.leaks.length} leaks, ${r.unexercised.length} unexercised, ${r.sealedNowhere.length} sealed or secret seen nowhere`);
  for (const l of r.leaks) console.log(`LEAK ${l.field} -> ${l.sink}`);
  process.exit(r.leaks.length || r.unexercised.length ? 1 : 0);
}
